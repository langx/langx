/* global Buffer, fetch */
/**
 * Prints `src/lib/emojiData.ts`, the list the reaction picker draws. From the
 * repository root:
 *
 *   node apps/mobile/scripts/build-emoji-data.mjs > apps/mobile/src/lib/emojiData.ts
 *
 * It writes nothing itself: the shell's redirect is the only write, so what
 * lands on disk is whatever the reader asked for, where they asked. The
 * output is already in Prettier's layout, so the file needs no formatting
 * pass afterwards.
 *
 * The source is `unicode-emoji-json` (MIT), which is Unicode's own emoji-test
 * data as JSON. It is fetched from a pinned version and checked against a
 * checksum rather than installed, because the app needs about 40 KB of it,
 * once, not an 800 KB package on every install. The script takes no
 * arguments: a pinned URL and a hash leave nothing to point it elsewhere, and
 * a changed file fails loudly instead of quietly changing the picker. To move
 * to a newer version, change both constants together.
 *
 * Only what a phone can draw is kept: emoji up to `MAX_EMOJI_VERSION`, the
 * base form of each (no skin-tone variants), and nothing from the "Component"
 * group, which holds bare skin tones and hair styles that are not emoji on
 * their own.
 */
import { createHash } from 'node:crypto'

/**
 * Emoji 13.1 — iOS 14.5 and Android 11. Anything newer is a blank box on a
 * phone that is still common, and a blank box in a picker is worse than a
 * missing emoji.
 */
const MAX_EMOJI_VERSION = 13.1

/** Unicode's group slugs, to the ids the app's labels are keyed by. */
const GROUPS = {
  smileys_emotion: 'smileys',
  people_body: 'people',
  animals_nature: 'nature',
  food_drink: 'food',
  travel_places: 'travel',
  activities: 'activities',
  objects: 'objects',
  symbols: 'symbols',
  flags: 'flags',
}

const SOURCE_URL = 'https://cdn.jsdelivr.net/npm/unicode-emoji-json@0.9.0/data-by-group.json'
const SOURCE_SHA256 = 'aa1fbede396c174a29af35e9dbb1f5a0e5de9b746c0b5a4bf1652562caf385ee'

const response = await fetch(SOURCE_URL)
if (!response.ok) throw new Error(`${SOURCE_URL}: HTTP ${response.status}`)
const body = Buffer.from(await response.arrayBuffer())
const digest = createHash('sha256').update(body).digest('hex')
if (digest !== SOURCE_SHA256) {
  throw new Error(`${SOURCE_URL}: sha256 ${digest}, expected ${SOURCE_SHA256}`)
}

const groups = JSON.parse(body.toString('utf8'))
const out = []
for (const group of groups) {
  const id = GROUPS[group.slug]
  if (!id) continue
  const list = group.emojis
    .filter((entry) => Number(entry.emoji_version) <= MAX_EMOJI_VERSION)
    // The separators the parser splits on must never be inside a name.
    .map((entry) => `${entry.emoji} ${entry.name.replace(/[|]/g, ' ')}`)
    .join('|')
  // Single-quoted, as Prettier writes it; a quote or backslash in a name
  // would need escaping, and none of Unicode's names has one.
  if (/['\\\n]/u.test(list)) throw new Error(`unexpected character in group ${id}`)
  out.push(`  {\n    id: '${id}',\n    list: '${list}',\n  },`)
}

process.stdout.write(`/**
 * Generated by \`apps/mobile/scripts/build-emoji-data.mjs\` from Unicode's
 * emoji data, by way of \`unicode-emoji-json\` (MIT). Do not edit; from the
 * repository root, regenerate with
 *
 *   node apps/mobile/scripts/build-emoji-data.mjs > apps/mobile/src/lib/emojiData.ts
 *
 * One string per group, \`emoji name|emoji name|…\`, because two thousand
 * two-field objects cost about twice the bytes in the bundle, and are parsed
 * into exactly that shape once, on first use, by \`emojiPicker.ts\`.
 */
export const EMOJI_GROUPS = [
${out.join('\n')}
] as const

export type EmojiGroupId = (typeof EMOJI_GROUPS)[number]['id']
`)
