/* global console */
/**
 * Writes `src/lib/emojiData.ts`, the list the reaction picker draws.
 *
 *   npm pack unicode-emoji-json && tar xzf unicode-emoji-json-*.tgz
 *   node scripts/build-emoji-data.mjs package/data-by-group.json
 *
 * The source is `unicode-emoji-json` (MIT), which is Unicode's own emoji-test
 * data as JSON. It is read from a path rather than installed, because the app
 * needs about 40 KB of it, once, not an 800 KB package on every install.
 *
 * Only what a phone can draw is kept: emoji up to `MAX_EMOJI_VERSION`, the
 * base form of each (no skin-tone variants), and nothing from the "Component"
 * group, which holds bare skin tones and hair styles that are not emoji on
 * their own.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Emoji 13.1 — iOS 14.5 and Android 11. Anything newer is a blank box on a
 * phone that is still common, and a blank box in a picker is worse than a
 * missing emoji.
 */
const MAX_EMOJI_VERSION = 13.1

/** Unicode's group slugs, to the ids the app's labels are keyed by. */
const GROUPS = {
  smileys_emotion: 'smileys',
  people_body: 'people',
  animals_nature: 'nature',
  food_drink: 'food',
  travel_places: 'travel',
  activities: 'activities',
  objects: 'objects',
  symbols: 'symbols',
  flags: 'flags',
}

const source = process.argv[2]
if (!source) {
  console.error('usage: node scripts/build-emoji-data.mjs <path to data-by-group.json>')
  process.exit(1)
}

const groups = JSON.parse(readFileSync(source, 'utf8'))
const out = []
for (const group of groups) {
  const id = GROUPS[group.slug]
  if (!id) continue
  const list = group.emojis
    .filter((entry) => Number(entry.emoji_version) <= MAX_EMOJI_VERSION)
    // The separators the parser splits on must never be inside a name.
    .map((entry) => `${entry.emoji} ${entry.name.replace(/[|]/g, ' ')}`)
    .join('|')
  out.push(`  { id: '${id}', list: ${JSON.stringify(list)} },`)
}

const target = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/emojiData.ts')
writeFileSync(
  target,
  `/**
 * Generated by \`scripts/build-emoji-data.mjs\` from Unicode's emoji data, by
 * way of \`unicode-emoji-json\` (MIT). Do not edit; rerun the script.
 *
 * One string per group, \`emoji name|emoji name|…\`, because two thousand
 * two-field objects cost about twice the bytes in the bundle, and are parsed
 * into exactly that shape once, on first use, by \`emojiPicker.ts\`.
 */
export const EMOJI_GROUPS = [
${out.join('\n')}
] as const

export type EmojiGroupId = (typeof EMOJI_GROUPS)[number]['id']
`,
)
console.log(`wrote ${target}`)
